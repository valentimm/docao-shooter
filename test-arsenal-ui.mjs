import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1536, height: 960 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(process.argv[2] || 'http://127.0.0.1:8136/');
  await page.waitForFunction(() => window.__gunThumbs > 0);
  await page.locator('.arsenal-crate').click();
  await page.waitForSelector('#menu[data-crate-state="inside"][data-view="arsenal"]');
  await page.locator('#arsenalApp .ar-class').first().waitFor({ state: 'visible' });
  assert.equal(await page.locator('#arsenalApp .ar-class').count(), 5);
  await page.screenshot({ path: 'screenshots/arsenal-classes.png' });
  await page.locator('#arsenalClassName').fill('Classe QA');
  await page.locator('#arsenalClassName').press('Tab');
  await page.locator('#arsenalApp [data-slot="primary"]').click();
  assert.equal(await page.locator('.ar-weapon-card').count(), 6);
  await page.locator('[data-weapon="0"]').click();
  await page.screenshot({ path: 'screenshots/arsenal-armas.png' });
  await page.locator('[data-action="customize"]').click();
  await page.locator('.ar-match-camos summary').click();
  await page.locator('[data-camo="2"]').click();
  const cv = page.locator('#arsenalApp canvas');
  const box = await cv.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width * .8, box.y + box.height * .6); await page.mouse.up();
  await page.screenshot({ path: 'screenshots/arsenal-customizar.png' });
  await page.locator('[data-part="mag"]').click();
  await page.locator('[data-piece="bolso"]').click();
  await page.locator('[data-action="equip"]').click();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('docao.classes'))[0]);
  assert.equal(saved.name, 'Classe QA'); assert.equal(saved.kits.rifle.mag, 'bolso');
  await page.locator('#arsenalApp [data-slot="secondary"]').click();
  await page.locator('[data-action="customize"]').click();
  await page.locator('[data-action="equip"]').click();
  await page.locator('#arsenalApp [data-slot="melee"]').click();
  await page.locator('[data-action="customize"]').click();
  await page.locator('[data-action="parts"]').click();
  assert.match(await page.locator('.ar-options').textContent(), /não possui peças/);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#arsenalApp').getAttribute('data-step'), '2');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#arsenalApp').getAttribute('data-step'), '1');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'screenshots/arsenal-mobile.png' });
  assert(await page.locator('.menu-content').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'sem overflow horizontal no celular');
  await page.locator('[data-action="close"]').click();
  await page.waitForSelector('#menu:not([data-crate-state])');
  await page.reload();
  await page.waitForFunction(() => window.__gunThumbs > 0);
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('docao.classes'))[0].kits.rifle.mag), 'bolso');
  assert.deepEqual(errors, []);
  console.log('OK: classes, categorias, prévia 3D, camuflagens, peças, persistência, secundária, corpo a corpo, Escape e celular.');
} finally { await browser.close(); }
